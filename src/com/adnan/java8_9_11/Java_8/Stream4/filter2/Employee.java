package com.adnan.java8_9_11.Java_8.Stream4.filter2;

public class Employee {
    private String name;
    private String empId;

    public Employee(String empId, String name) {
        this.empId = empId;
        this.name = name;
    }

    public String getEmpId() {
        return empId;
    }

    public String getName() {
        return name;
    }
}
